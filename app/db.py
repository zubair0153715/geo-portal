"""Database layer: SQLite locally, Postgres when DATABASE_URL is set.

Default: stdlib sqlite3 only (zero new dependencies). When
config.DATABASE_URL is set, connects via psycopg (see requirements.txt).

Compat shim (so all 36 helper signatures stay identical):
  - `?` placeholders are translated to `%s` for Postgres (quoted literals untouched)
  - `INTEGER PRIMARY KEY AUTOINCREMENT` becomes GENERATED BY DEFAULT AS IDENTITY
  - INSERT helpers use `RETURNING id` instead of cursor.lastrowid
  - rows come back as dicts in both backends (callers do dict(r))
"""

import json
import os
import sqlite3
from datetime import datetime, timedelta, timezone

from . import config

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    email      TEXT UNIQUE NOT NULL,
    pw_hash    TEXT NOT NULL,
    created    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS businesses (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id    INTEGER NOT NULL REFERENCES users(id),
    name       TEXT NOT NULL,
    website    TEXT NOT NULL,
    phrases    TEXT NOT NULL,          -- JSON array of customer search phrases
    created    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS connections (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    business_id    INTEGER NOT NULL REFERENCES businesses(id),
    provider       TEXT NOT NULL,      -- google | openai | perplexity | gemini | wordpress
    encrypted_blob TEXT NOT NULL,     -- Fernet-encrypted JSON (vault)
    status         TEXT NOT NULL DEFAULT 'connected',  -- connected | error | not_configured
    updated        TEXT NOT NULL,
    UNIQUE (business_id, provider)
);

CREATE TABLE IF NOT EXISTS checks (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    business_id  INTEGER NOT NULL REFERENCES businesses(id),
    provider_ai  TEXT NOT NULL,        -- openai | perplexity | gemini | manual
    phrase       TEXT NOT NULL,
    answer_text  TEXT NOT NULL,
    mention_bool INTEGER NOT NULL,     -- 0/1: was the business mentioned?
    competitors  TEXT NOT NULL DEFAULT '[]',  -- JSON array of rival names found
    score        INTEGER NOT NULL,     -- 0..100 visibility score for this check
    ran_at       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_checks_biz_time ON checks (business_id, ran_at);

CREATE TABLE IF NOT EXISTS reports (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    business_id INTEGER NOT NULL REFERENCES businesses(id),
    html_path   TEXT NOT NULL,
    html        TEXT,                  -- full report HTML (authoritative on ephemeral disks)
    sent_at     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS agent_runs (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    business_id INTEGER NOT NULL REFERENCES businesses(id),
    agent       TEXT NOT NULL,        -- scout | content | reporter
    status      TEXT NOT NULL,        -- ok | skipped | error
    detail      TEXT NOT NULL DEFAULT '',
    ran_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_agent_runs ON agent_runs (business_id, agent, ran_at);

-- In-portal AI client agent (support) ---------------------------------------
CREATE TABLE IF NOT EXISTS leads (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    name       TEXT NOT NULL DEFAULT '',
    email      TEXT NOT NULL,
    business   TEXT NOT NULL DEFAULT '',
    website    TEXT NOT NULL DEFAULT '',
    source     TEXT NOT NULL DEFAULT 'chat_widget',  -- chat_widget | manual
    status     TEXT NOT NULL DEFAULT 'new',          -- new | contacted | client | dropped
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads (status, created_at);

CREATE TABLE IF NOT EXISTS support_conversations (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id    INTEGER NULL REFERENCES users(id),    -- NULL for logged-out visitors
    lead_id    INTEGER NULL REFERENCES leads(id),    -- NULL until a visitor is captured
    messages   TEXT NOT NULL DEFAULT '[]',           -- JSON array of {role, text, at}
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS escalations (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    conversation_id INTEGER NOT NULL REFERENCES support_conversations(id),
    reason          TEXT NOT NULL,    -- pricing | commitment
    summary         TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'open',   -- open | handled
    created_at      TEXT NOT NULL,
    handled_at      TEXT
);
CREATE INDEX IF NOT EXISTS idx_escalations_status ON escalations (status, created_at);
"""


def _use_pg() -> bool:
    """True when DATABASE_URL is set — evaluated per call so tests can flip it."""
    return bool(config.DATABASE_URL)


def _translate(sql: str) -> str:
    """Translate SQLite `?` placeholders to psycopg `%s`.

    Single/double-quoted literals are passed through untouched (including
    doubled-quote escapes). No-op when not on Postgres.
    """
    if not _use_pg():
        return sql
    out, i, n = [], 0, len(sql)
    while i < n:
        ch = sql[i]
        if ch in ("'", '"'):
            j = i + 1
            while j < n:
                if sql[j] == ch:
                    if j + 1 < n and sql[j + 1] == ch:  # escaped quote ('')
                        j += 2
                        continue
                    break
                j += 1
            out.append(sql[i:j + 1])
            i = j + 1
        elif ch == "?":
            out.append("%s")
            i += 1
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def _connect():
    if _use_pg():
        import psycopg
        from psycopg.rows import dict_row
        return psycopg.connect(config.DATABASE_URL, row_factory=dict_row)
    os.makedirs(os.path.dirname(config.DB_PATH), exist_ok=True)
    conn = sqlite3.connect(config.DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def _exec(conn, sql, params=()):
    """Execute with placeholder translation; INSERTs get RETURNING id on Postgres."""
    q = _translate(sql)
    if _use_pg() and q.lstrip().upper().startswith("INSERT"):
        q += " RETURNING id"
    return conn.execute(q, params)


def _insert_id(cur):
    """New row id for an INSERT executed via _exec."""
    if _use_pg():
        return cur.fetchone()["id"]
    return cur.lastrowid


def _schema_sql() -> str:
    s = SCHEMA
    if _use_pg():
        s = s.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                      "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    return s


def _exec_script(conn, sql: str) -> None:
    if _use_pg():
        for stmt in (part.strip() for part in sql.split(";")):
            if stmt:
                conn.execute(_translate(stmt))
    else:
        conn.executescript(sql)


def init_db() -> None:
    with _connect() as conn:
        _exec_script(conn, _schema_sql())
    # reports.html was added after the first schema shipped — keep old DBs working.
    with _connect() as conn:
        if _use_pg():
            conn.execute("ALTER TABLE reports ADD COLUMN IF NOT EXISTS html TEXT")
        else:
            try:
                conn.execute("ALTER TABLE reports ADD COLUMN html TEXT")
            except sqlite3.OperationalError:
                pass  # already there (fresh CREATE TABLE includes it)


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


# --- users -----------------------------------------------------------------
def create_user(email: str, pw_hash: str) -> int:
    with _connect() as conn:
        cur = _exec(
            conn,
            "INSERT INTO users (email, pw_hash, created) VALUES (?, ?, ?)",
            (email.strip().lower(), pw_hash, now_iso()),
        )
        return _insert_id(cur)


def get_user_by_email(email: str):
    with _connect() as conn:
        return _exec(
            conn,
            "SELECT * FROM users WHERE email = ?", (email.strip().lower(),)
        ).fetchone()


def get_user(user_id: int):
    with _connect() as conn:
        return _exec(
            conn, "SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()


