def last_agent_runs(business_id: int) -> dict:
    """Latest run per agent name -> row (or missing key if never ran)."""
    with _connect() as conn:
        rows = _exec(
            conn,
            """SELECT * FROM agent_runs WHERE business_id = ?
               ORDER BY ran_at DESC""",
            (business_id,),
        ).fetchall()
    latest = {}
    for r in rows:
        latest.setdefault(r["agent"], r)
    return latest


