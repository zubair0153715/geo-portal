def link_conversation_lead(conv_id: int, lead_id: int) -> None:
    with _connect() as conn:
        _exec(
            conn,
            "UPDATE support_conversations SET lead_id = ?, updated_at = ? WHERE id = ?",
            (lead_id, now_iso(), conv_id))


def append_message(conv_id: int, role: str, text: str) -> None:
    if role not in ("user", "assistant", "system"):
        raise ValueError("Unknown message role.")
    with _connect() as conn:
        row = _exec(
            conn,
            "SELECT messages FROM support_conversations WHERE id = ?",
            (conv_id,)).fetchone()
        if not row:
            raise ValueError("Conversation not found.")
        msgs = json.loads(row["messages"] or "[]")
        msgs.append({"role": role, "text": text, "at": now_iso()})
        _exec(
            conn,
            "UPDATE support_conversations SET messages = ?, updated_at = ? WHERE id = ?",
            (json.dumps(msgs), now_iso(), conv_id))


def conversation_messages(conv_id: int) -> list:
    row = get_conversation(conv_id)
    if not row:
        return []
    return json.loads(row["messages"] or "[]")


def list_conversations(limit: int = 50):
    with _connect() as conn:
        return _exec(
            conn,
            """SELECT c.*, u.email AS user_email, l.name AS lead_name, l.email AS lead_email
               FROM support_conversations c
               LEFT JOIN users u ON u.id = c.user_id
               LEFT JOIN leads l ON l.id = c.lead_id
               ORDER BY c.updated_at DESC LIMIT ?""",
            (limit,)).fetchall()


# --- escalations -------------------------------------------------------------------
def create_escalation(conversation_id: int, reason: str, summary: str) -> int:
    if reason not in ("pricing", "commitment"):
        raise ValueError("Unknown escalation reason.")
    with _connect() as conn:
        cur = _exec(
            conn,
            """INSERT INTO escalations (conversation_id, reason, summary, status, created_at)
               VALUES (?, ?, ?, 'open', ?)""",
            (conversation_id, reason, summary[:2000], now_iso()),
        )
        return _insert_id(cur)


def get_escalation(esc_id: int):
    with _connect() as conn:
        return _exec(
            conn,
            """SELECT e.*, c.user_id, c.lead_id, u.email AS user_email,
                      l.name AS lead_name, l.email AS lead_email
               FROM escalations e
               JOIN support_conversations c ON c.id = e.conversation_id
               LEFT JOIN users u ON u.id = c.user_id
               LEFT JOIN leads l ON l.id = c.lead_id
               WHERE e.id = ?""",
            (esc_id,)).fetchone()


def list_escalations(open_only: bool = True, limit: int = 100):
    with _connect() as conn:
        q = ("""SELECT e.*, u.email AS user_email, l.name AS lead_name, l.email AS lead_email
                FROM escalations e
                JOIN support_conversations c ON c.id = e.conversation_id
                LEFT JOIN users u ON u.id = c.user_id
                LEFT JOIN leads l ON l.id = c.lead_id
                %s ORDER BY e.id DESC LIMIT ?""")
        where = "WHERE e.status = 'open'" if open_only else ""
        return _exec(conn, q % where, (limit,)).fetchall()


def mark_escalation_handled(esc_id: int) -> None:
    with _connect() as conn:
        _exec(
            conn,
            "UPDATE escalations SET status = 'handled', handled_at = ? WHERE id = ?",
            (now_iso(), esc_id))
