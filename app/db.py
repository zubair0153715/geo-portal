def checks_since(business_id: int, days: int):
    """All checks in the last N days, oldest first (for trend charts)."""
    cutoff = (datetime.now(timezone.utc) - timedelta(days=int(days))).isoformat()
    with _connect() as conn:
        return _exec(
            conn,
            """SELECT * FROM checks WHERE business_id = ?
               AND ran_at >= ?
               ORDER BY ran_at ASC""",
            (business_id, cutoff),
        ).fetchall()


