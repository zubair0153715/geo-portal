# ------------------------------------------------- placeholder shim ----
@pytest.mark.parametrize("given,pg_want", [
    ("SELECT * FROM users WHERE id = ?", "SELECT * FROM users WHERE id = %s"),
    ("VALUES (?, ?, ?)", "VALUES (%s, %s, %s)"),
    ("status = 'connected' AND id = ?", "status = 'connected' AND id = %s"),
    ("a = ? AND b = 'it''s ?' AND c = ?", "a = %s AND b = 'it''s ?' AND c = %s"),
])
def test_translate_placeholders(monkeypatch, given, pg_want):
    monkeypatch.setattr(config, "DATABASE_URL", "postgresql://x")
    assert db._translate(given) == pg_want


def test_translate_noop_on_sqlite(monkeypatch):
    monkeypatch.setattr(config, "DATABASE_URL", "")
    sql = "SELECT * FROM users WHERE id = ? AND status = 'a?b'"
    assert db._translate(sql) == sql


def test_schema_pg_identity(monkeypatch):
    monkeypatch.setattr(config, "DATABASE_URL", "postgresql://x")
