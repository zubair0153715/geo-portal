# ------------------------------------------------- DB-backed reports ----
def test_report_served_from_db_html_no_file(client):
    c, biz = client
    fname = f"report_{biz}_2026-10-02_db.html"
    rid = db.insert_report(biz, f"/nonexistent/{fname}")  # file does NOT exist
    db.update_report_html(rid, "<html><body>db copy</body></html>")
    r = c.get(f"/reports/files/{fname}?business_id={biz}")
    assert r.status_code == 200
    assert b"db copy" in r.content


def test_report_db_copy_download_attachment(client):
    c, biz = client
    fname = f"report_{biz}_2026-10-02_dl.html"
    rid = db.insert_report(biz, f"/nonexistent/{fname}")
    db.update_report_html(rid, "<html><body>db copy</body></html>")
    r = c.get(f"/reports/files/{fname}?business_id={biz}&download=1")
    assert r.status_code == 200
    assert "attachment" in r.headers.get("content-disposition", "")


