# ------------------------------------------------- self-monitor ----
def test_self_monitor_idempotent(tmp_path, monkeypatch):
    monkeypatch.setattr(config, "DB_PATH", str(tmp_path / "sm.db"))
    monkeypatch.setattr(config, "DEMO_MODE", False)
    monkeypatch.setattr(config, "PUBLIC_URL", "https://example.com")
    from app import self_monitor
    db.init_db()
    db.create_user("owner@example.com", "hash")
    first = self_monitor.ensure_self_monitor()
    second = self_monitor.ensure_self_monitor()
    assert first["ok"] and second["ok"]
    assert first["created"] is True and second["created"] is False
    assert first["business_id"] == second["business_id"]
    uid = db.get_user_by_email("owner@example.com")["id"]
    names = [b["name"] for b in db.list_businesses(uid)]
    assert names.count("AI Visibility Portal") == 1


