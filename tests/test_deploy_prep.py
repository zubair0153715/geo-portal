# ------------------------------------------------- live Postgres (opt-in) ----
@pytest.mark.skipif(not os.environ.get("DATABASE_URL"),
                    reason="needs a live Postgres (DATABASE_URL)")
def test_postgres_roundtrip(monkeypatch):
    """Real round-trip against Postgres when DATABASE_URL is provided."""
    monkeypatch.setattr(config, "DATABASE_URL", os.environ["DATABASE_URL"])
    db.init_db()
    uid = db.create_user("pg@example.com", "hash")
    assert isinstance(uid, int)
    biz = db.create_business(uid, "PG Biz", "https://pg.example.com", ["p1"])
    assert isinstance(biz, int)
    assert db.get_user_by_email("pg@example.com")["email"] == "pg@example.com"
    rid = db.insert_report(biz, "/tmp/x.html")
    db.update_report_html(rid, "<html>pg</html>")
    rows = db.list_reports(biz)
    assert dict(rows[0])["html"] == "<html>pg</html>"
    db.upsert_connection(biz, "gemini", "blob")
    db.upsert_connection(biz, "gemini", "blob2")  # ON CONFLICT path
    assert db.get_connection(biz, "gemini")["encrypted_blob"] == "blob2"
